import { describe, expect, test } from "bun:test";
import { INVESTIGATE_COMMAND } from "./investigate";
import { PR_COMMAND } from "./pr";
import { STATUS_COMMAND } from "./status";
import { WORK_COMMAND } from "./work";

const COMMANDS = [
    INVESTIGATE_COMMAND,
    PR_COMMAND,
    STATUS_COMMAND,
    WORK_COMMAND,
];

describe("generated slash commands", () => {
    test("include their generated-file notice", () => {
        for (const command of COMMANDS) {
            expect(command).toContain("<!-- Generated by craftpath.");
        }
    });

    test("render every standalone CP marker as a Markdown fence", () => {
        for (const command of COMMANDS) {
            expect(command).not.toMatch(/^CP$/m);
        }

        expect(WORK_COMMAND.match(/^```$/gm)).toHaveLength(12);
        expect(INVESTIGATE_COMMAND.match(/^```$/gm)).toHaveLength(2);
    });

    test("preserve command arguments for Claude Code", () => {
        expect(WORK_COMMAND).toContain("Deliver this requirement: $ARGUMENTS");
        expect(INVESTIGATE_COMMAND).toContain("Investigate: $ARGUMENTS");
        expect(PR_COMMAND).toContain("Resolve review comments on: $ARGUMENTS");
    });

    test("makes task skill loading explicit", () => {
        expect(WORK_COMMAND).toContain("### Skill contract");
        expect(WORK_COMMAND).toContain("explicitly preload every declared");
        expect(WORK_COMMAND).toContain("If a declared skill is missing");
    });
});
